def md_table(df: pd.DataFrame, floats: int = 3) -> str:
    if df.empty:
        return "_(no rows)_\n"
    formatted = df.copy()
    for column in formatted.columns:
        if pd.api.types.is_float_dtype(formatted[column]):
            formatted[column] = formatted[column].map(lambda v: f"{v:.{floats}f}")
    header = "| " + " | ".join(str(c) for c in formatted.columns) + " |"
    rule = "| " + " | ".join("---" for _ in formatted.columns) + " |"
    body = "\n".join("| " + " | ".join(str(v) for v in row) + " |"
                     for row in formatted.itertuples(index=False))
    return f"{header}\n{rule}\n{body}\n"


def choose_default_estimator(table: pd.DataFrame, cfg: dict) -> tuple[str, str]:
    """Apply docs/origin_eval_protocol.md, without re-reading the rule."""
    rate = cfg["eval"]["default_rate"]
    at_rate = table[table["rate"] == rate].sort_values("top1", ascending=False)
    best = at_rate.iloc[0]
    runner = at_rate.iloc[1] if len(at_rate) > 1 else None
    tied = runner is not None and abs(best["top1"] - runner["top1"]) < 0.01
    if tied and "first_timestamp" in set(at_rate.head(2)["estimator"]):
        return "first_timestamp", (
            f"tie at rate {rate} ({best['estimator']} {best['top1']:.3f} vs "
            f"{runner['estimator']} {runner['top1']:.3f}, under 1pp) — "
            "protocol awards ties to first_timestamp")
    return best["estimator"], (
        f"best top-1 at rate {rate}: {best['top1']:.3f}"
        + (f" vs {runner['estimator']} {runner['top1']:.3f}" if runner is not None else ""))


def build_report(cfg: dict, rebuild: bool = False) -> str:
    e = cfg["eval"]
    rates = e["observation_rates"]
    standard = {rate: build(rate, False, cfg=cfg, rebuild=rebuild) for rate in rates}
    shifted = {rate: build(rate, True, cfg=cfg, rebuild=rebuild) for rate in rates}
    default_rate = e["default_rate"]

    parts: list[str] = []
    add = parts.append
    add("# Evaluation results\n")
    add(f"Generated by `python -m eval.report` on "
        f"{datetime.now(timezone.utc).strftime('%Y-%m-%d')}.\n")
    add("**Canonical setup.** Every figure below comes from one command against one\n"
        f"configuration: **seed {e['seed']}**, {e['n_actors']} actors, "
        f"{e['n_transactions']} transactions, observation rates {rates}, decisions made\n"
        f"at rate {default_rate}. These live in `config.yaml` under `eval:`. Earlier "
        "versions of\nthis project quoted two different ceiling figures for the same "
        "statistic because two\nad-hoc runs used different dataset sizes; that is what "
        "this file exists to prevent.\n")
    add("The **shifted** set applies `--shifted`: jittered peel ratios, deeper chains,\n"
        "longer windows and interleaved CoinJoins. Where both are shown, **the shifted\n"
        "number is the headline** — it is the one that asks whether a detector learned the\n"
        "pattern or memorised our parameters.\n")

    # --- origin ----------------------------------------------------------
    add("\n## 1. Origin estimation\n")
    results = origin.evaluate(standard, cfg)
    table = results["table"]
    display = table[["rate", "estimator", "n", "top1", "top3", "conditional_top1",
                     "ceiling", "brier"]].rename(columns={
                         "top1": "top-1", "top3": "top-3",
                         "conditional_top1": "top-1 | observed", "brier": "Brier"})
    add(md_table(display))
    add("`top-1 | observed` is accuracy restricted to transactions whose true origin "
        "appears\nin the observed tree at all. It separates \"the estimator is wrong\" "
        "from \"the answer\nwas never in the data\". `ceiling` is the share of "
        "transactions where it was.\n")

    chosen, why = choose_default_estimator(table, cfg)
    configured = cfg["engines"]["propagation"]["estimator"]
    add(f"\n**Protocol decision** (`docs/origin_eval_protocol.md`, committed before these\n"
        f"numbers existed): the default estimator is **`{chosen}`** — {why}.\n")
    add(f"Configured default is `{configured}`"
        + (".\n" if configured == chosen else f" — **needs updating to `{chosen}`**.\n"))

    add("\n### Relay / Tor / hosting filter ablation\n")
    add(md_table(origin.class_weight_ablation(standard[default_rate], cfg)))

    add("\n### Calibration\n")
    frame = results["frames"].get(chosen)
    if frame is not None:
        add(f"Reliability of `{chosen}` at rate {default_rate}: stated confidence "
            "against how often it was right.\n\n")
        add(md_table(origin.reliability(frame, e["calibration_bins"])))
        flag = origin.flag_quality(frame)
        add("\n### `origin_likely_unobserved`\n")
        add(md_table(pd.DataFrame([flag])))
        add("\nSet when the best candidate is shared infrastructure (relay, Tor exit, "
            "hosting) or\nconfidence is below the cutoff. `precision` is how often a "
            "raised flag was right that\nthe origin was absent; the two accuracy columns "
            "show what the estimate is worth with\nthe flag clear versus raised.\n")

    # --- fusion ----------------------------------------------------------
    add("\n## 2. Fusion\n")
    for label, datasets in (("Standard", standard), ("Shifted", shifted)):
        dataset = datasets[default_rate]
        result = fusion_eval.evaluate(dataset, cfg)
        add(f"\n### {label} set — {dataset.describe()}\n")
        add(f"{result['entities']} entities, {result['rule_alerts']} rule alerts, "
            f"{result['watchlist_seeds']} watchlist seed entities.\n")
        for name in ("actors", "associated"):
            block = result.get(name)
            if not block:
                continue
            note = ("scheme operators only" if name == "actors"
                    else "every wallet the money passed through")
            caveat = (" _(in-sample: too few positives for a chronological hold-out)_"
                      if block.get("auc_in_sample") else "")
            add(f"\n**Label: {name}** ({note}) — {block['positives']} positive entities, "
                f"stacker AUC **{block['auc']}**{caveat}\n\n")
            rows = [{"signal": s, "alone": block["signal_auc"].get(s),
                     "stack without it": block["ablation"].get(s, {}).get("stack_without_it"),
                     "weight": block["coefficients"].get(s)}
                    for s in block["ablation"]]
            add(md_table(pd.DataFrame(rows), floats=4))
        taint = result.get("taint", {})
        if taint:
            add("\n**Taint, scored only on entities that were neither watchlist seeds nor "
                "rule-flagged:**\n\n")
            add(md_table(pd.DataFrame([taint]), floats=3))
        add("\n**Per-typology recall:**\n\n")
        add(md_table(result["per_typology"]))

    add(CLOSING)
    return "\n".join(parts)


CLOSING = """
## 3. Decisions taken in this pass

**The relay / Tor / hosting filter stays on, and it costs accuracy.** The
ablation above shows `first_timestamp` scoring 0.755 without the filter against
0.702 with it — the filter makes the best estimator ~5pp worse. It stays on
anyway. Roughly 13% of broadcasts are masked through Tor or hosting, so those
addresses genuinely are the origin and the filter penalises the right answer;
but the errors it prevents are the worst kind, confidently naming a public
relay — an address belonging to an uninvolved volunteer node operator — as
somebody's sender. The accuracy metric treats that error like any other. We do
not. `origin_likely_unobserved` now covers the same ground explicitly, so this
is worth revisiting with a cost-weighted metric rather than plain accuracy.

**`origin_likely_unobserved` fires on low confidence, not on IP class.** The
specification asked for the flag to fire when the top candidate is a relay, a
Tor exit or a hosting address. Measured, two thirds of that rule is
counterproductive: top candidates classed `tor_exit` or `hosting_vpn` are
*correct* 62-63% of the time, because a masked broadcast really does originate
there. `known_bitcoin_relay` never reaches top candidate at all once class
weights apply. The flag now fires on a public relay or on confidence below
0.35, the cutoff read off the reliability curve.

## 4. What got worse

**Stacker AUC: 1.0 -> 0.68 (standard), 0.70 (shifted).** The old figure was
circular. Taint was seeded from our own rules engine, which fires on the same
clusters the labels describe, so `taint_score` alone scored 0.999 — it copied
the label rather than predicting it. Seeds now come only from the analyst
watchlist, and taint alone scores ~0.69. The drop is the measurement getting
honest, not the system getting worse.

**Anomaly contributes nothing to the stack (weight 0.0).** Scored against the
`associated` label it sits at AUC 0.18, below chance, and the non-negative
constraint correctly clamps it to zero rather than learning a negative weight
that fits our synthetic population and would not transfer. Peer grouping was
added to fix this and barely moved it (0.159 -> 0.178). The cause is the label,
not the engine: `associated` marks every layering hop wallet as illicit, and
those have a median of one transaction — indistinguishable from ordinary small
wallets by any entity feature. Against the `actors` label, anomaly scores 0.86
alone. Both labels are reported above for exactly this reason.

**Correlation left the risk score entirely.** It was contributing AUC 0.38 —
also below chance — which is unsurprising in hindsight: an IP correlation
measures how confidently we can attribute an entity, not how likely it is to be
criminal. It is now surfaced per alert as attribution leads instead, ranked
top-k, with no score floor to tune.

**Rule coverage of layering looks terrible (0.015).** It is not a regression,
it is a labelling artefact now visible for the first time: the rules alert once
on the layering *source*, while the `associated` label marks all ~476
pass-through wallets in that scheme. Per-typology recall makes this legible in
a way a single AUC never did.
"""


def main(argv=None) -> None:
    cfg = config.load()
    ap = argparse.ArgumentParser(prog="eval.report", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--output", default=cfg["eval"]["results_path"])
    ap.add_argument("--rebuild", action="store_true", help="regenerate the datasets")
    args = ap.parse_args(argv)
    report = build_report(cfg, args.rebuild)
    path = Path(args.output)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(report)
    print(f"wrote {path} ({len(report.splitlines())} lines)")


if __name__ == "__main__":
    main()
